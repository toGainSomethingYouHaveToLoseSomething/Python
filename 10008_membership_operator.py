h = "hello"
print("l" in h)  # True, because "l" is a member of the string "hello"
print("x" in h)  # False, because "x" is not a member of the string "hello"

l = [1, 2, 3, 4, 5]
print(3 in l)  # True, because 3 is a member of the list
print(6 in l)  # False, because 6 is not a member of the list

print(3 not in l)  # False, because 3 is a member of the list
print(6 not in l)  # True, because 6 is not a member of the list